import json, os, hashlib, glob, datetime
meta = json.load(open("/tmp/meta.json"))
LICENSE_GLOBS = ["LICENSE*","License*","license*","COPYING*","NOTICE*","COPYRIGHT*","UNLICENSE*"]
deps = []
for p in meta["packages"]:
    if p.get("source") is None:   # workspace / path deps (our own) -> skip
        continue
    crate_dir = os.path.dirname(p["manifest_path"])
    files = []
    for g in LICENSE_GLOBS:
        for f in glob.glob(os.path.join(crate_dir, g)):
            if os.path.isfile(f):
                files.append(f)
    files = sorted(set(files))
    texts = []
    for f in files:
        try:
            t = open(f, encoding="utf-8", errors="replace").read().strip()
            if t:
                texts.append(t)
        except Exception:
            pass
    deps.append({"name": p["name"], "version": p["version"],
                 "license": p.get("license") or "(SPDX field absent)",
                 "repo": p.get("repository") or "",
                 "texts": texts})
deps.sort(key=lambda d:(d["name"].lower(), d["version"]))

# dedup license texts by content
text_index = {}   # hash -> (text, [pkg labels])
for d in deps:
    for t in d["texts"]:
        h = hashlib.sha256(t.encode("utf-8","replace")).hexdigest()
        text_index.setdefault(h, [t, []])[1].append(f'{d["name"]} {d["version"]}')

out = []
out.append("# Third-Party Notices")
out.append("")
out.append("Viaticum is licensed under AGPL-3.0-only. It links the third-party")
out.append("dependencies listed below, each under its own license. Their copyright")
out.append("notices and license texts are reproduced here as required by those licenses.")
out.append("")
out.append(f"Generated from `cargo metadata` on {datetime.date.today().isoformat()}. "
           f"{len(deps)} dependencies.")
out.append("")
out.append("Regenerated by `scripts/gen-third-party-notices.py` (not hand-edited).")
out.append("")
out.append("## Dependency inventory")
out.append("")
out.append("| Crate | Version | License (SPDX) |")
out.append("|-------|---------|----------------|")
for d in deps:
    out.append(f'| {d["name"]} | {d["version"]} | {d["license"]} |')
out.append("")
out.append("## License texts")
out.append("")
nofile = [f'{d["name"]} {d["version"]} ({d["license"]})' for d in deps if not d["texts"]]
if nofile:
    out.append("The following crates ship no license file in their crate root; the "
               "canonical SPDX text of the license named in their manifest applies:")
    out.append("")
    for n in nofile:
        out.append(f"- {n}")
    out.append("")
# emit unique texts, ordered by number of users desc then first pkg
items = sorted(text_index.values(), key=lambda v:(-len(v[1]), v[1][0].lower()))
for i,(text, pkgs) in enumerate(items, 1):
    uniq = sorted(set(pkgs), key=str.lower)
    out.append(f"### License text #{i}  — used by {len(uniq)} crate(s)")
    out.append("")
    out.append("Applies to: " + ", ".join(uniq))
    out.append("")
    out.append("```")
    out.append(text)
    out.append("```")
    out.append("")
open("THIRD-PARTY-NOTICES.md","w",encoding="utf-8").write("\n".join(out))
print("deps:", len(deps), "| unique license texts:", len(items), "| crates w/o bundled file:", len(nofile))
