/// The table row that serves `k`: the smallest K' >= k. Panics above 56 403 (the raptorq limit;
/// the daemon refuses such blocks before encoding).
fn row(k: u32) -> (u32, u32, u32) {
    let i = TABLE.partition_point(|&(k_prime, _, _)| k_prime < k);
    assert!(i < TABLE.len(), "K = {k} exceeds the RaptorQ limit");
    TABLE[i]
}

/// `L(K) = K' + S(K') + H(K')`: the intermediate symbols RaptorQ builds for K source symbols.
pub fn intermediate_symbols(k: u32) -> u32 {
    let (k_prime, s, h) = row(k);
    k_prime + s + h
}

/// `(K', S, H)` of the row that serves `k` (for the unit that checks the table against raptorq).
pub fn table_row(k: u32) -> (u32, u32, u32) {
    row(k)
}

/// What the encoder holds beyond its input for K source symbols of T bytes: K copies of the
/// source symbols, L intermediate symbols, and the plan (upper bound):
/// `(K + L(K)) * T + PLAN_BYTES_PER_SOURCE_SYMBOL * K`.
pub fn encoder_bytes(k: u32, t: u16) -> u64 {
    (k as u64 + intermediate_symbols(k) as u64) * t as u64 + PLAN_BYTES_PER_SOURCE_SYMBOL * k as u64
}
